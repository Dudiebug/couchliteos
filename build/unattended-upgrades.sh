#!/bin/bash
# Prints the unattended-upgrades configuration for the image, given the live-build package
# lists. configure.sh installs it as /etc/apt/apt.conf.d/52couchliteos-unattended.
#
# - Origins: only Debian security fixes for trixie, Google Chrome and Tailscale. Nothing from
#   main or backports moves between releases, so the box stays the tested system plus fixes.
# - Held: every package the build pins (build/apt-pins.sh) and the ones the image rebuilds
#   or takes from backports, so a security run cannot replace them.
# - Never restarts the box; couchliteos-security-update.service runs unattended-upgrade
#   itself (apt's own daily timers are switched off here), so it can wait while the box is
#   in use.
#
# The file sorts after 50unattended-upgrades and clears its lists first: apt.conf lists add
# up across files.
set -Eeuo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
# Rebuilt by hooks/live/0050-cage.hook.chroot against the image's wlroots, and the one
# package taken from trixie-backports.
EXTRA_HELD=(cage gamescope)

mapfile -t pinned < <("$ROOT/build/apt-pins.sh" "$@" | sed -n 's/^Package: //p')
mapfile -t held < <(printf '%s\n' "${pinned[@]}" "${EXTRA_HELD[@]}" | sed '/^$/d' | LC_ALL=C sort -u)

cat <<'EOF'
// Generated by build/unattended-upgrades.sh. Security fixes between CouchLiteOS releases.
APT::Periodic::Update-Package-Lists "0";
APT::Periodic::Unattended-Upgrade "0";
APT::Periodic::Download-Upgradeable-Packages "0";
APT::Periodic::AutocleanInterval "0";

#clear Unattended-Upgrade::Allowed-Origins;
#clear Unattended-Upgrade::Origins-Pattern;
Unattended-Upgrade::Origins-Pattern {
        "origin=Debian,codename=trixie-security,label=Debian-Security";
        "origin=Google LLC";
        "origin=Tailscale";
};

#clear Unattended-Upgrade::Package-Blacklist;
Unattended-Upgrade::Package-Blacklist {
EOF
for package in "${held[@]}"; do
  printf '        "^%s$";\n' "${package//./\\.}"
done
cat <<'EOF'
};

Unattended-Upgrade::Automatic-Reboot "false";
Unattended-Upgrade::Automatic-Reboot-WithUsers "false";
Unattended-Upgrade::MinimalSteps "true";
Unattended-Upgrade::OnlyOnACPower "false";
Unattended-Upgrade::Skip-Updates-On-Metered-Connections "true";
Unattended-Upgrade::Remove-Unused-Dependencies "false";
Unattended-Upgrade::Remove-New-Unused-Dependencies "false";
Unattended-Upgrade::SyslogEnable "true";
EOF
